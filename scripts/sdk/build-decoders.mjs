import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";

// Emit `@dambi/core/decoders` from the committed Registry snapshot
// (registryV2/decoder-snapshots/full, made by `npm run build:decoder-snapshot`).
// The artifact is embedded as a JS string so its exact bytes — and therefore its
// pinned digest — survive Node and bundlers without fetch or file paths. This
// step never regenerates the snapshot: a package version pins one artifact.
const root = new URL("../../", import.meta.url);
const source = new URL("registryV2/decoder-snapshots/full/", root);
const output = new URL("packages/core/dist/", root);

// The package build runs tsc first: decoders.d.ts imports the emitted types.
await access(new URL("index.d.ts", output));
const [artifact, metaText] = await Promise.all([
  readFile(new URL("snapshot.json", source), "utf8"),
  readFile(new URL("snapshot.meta.json", source), "utf8"),
]);
const meta = JSON.parse(metaText);
const digest = `0x${createHash("sha256").update(artifact, "utf8").digest("hex")}`;
if (digest !== meta.digest) {
  throw new Error(`Decoder snapshot digest ${digest} does not match snapshot.meta.json ${meta.digest}`);
}
const container = JSON.parse(artifact);
if (container.schema_version !== 1 || container.bundles.length !== meta.bundle_count) {
  throw new Error("Decoder snapshot container does not match snapshot.meta.json");
}
if (meta.rejected_by_core === null) {
  throw new Error("Decoder snapshot was generated with --no-verify; regenerate it with the Core gate");
}

const info = { name: meta.name, bundleCount: meta.bundle_count, bytes: meta.bytes };
await writeFile(new URL("decoders.js", output), [
  "// Generated by scripts/sdk/build-decoders.mjs from registryV2/decoder-snapshots/full. Do not edit.",
  `const artifact = ${JSON.stringify(artifact)};`,
  `export const decoderSnapshot = Object.freeze({ artifact, expectedDigest: ${JSON.stringify(digest)} });`,
  `export const decoderSnapshotInfo = Object.freeze(${JSON.stringify(info)});`,
  "",
].join("\n"));
await writeFile(new URL("decoders.d.ts", output), [
  'import type { DecoderSnapshot } from "./index.js";',
  "/** Registry decoder snapshot pinned to this package version; pass as `CoreConfig.decoderSnapshot`. */",
  "export declare const decoderSnapshot: DecoderSnapshot;",
  "/** `bytes` is the artifact's UTF-8 size: `CoreLimits.maxDecoderBytes` must be at least this. */",
  "export declare const decoderSnapshotInfo: {",
  "  readonly name: string;",
  "  readonly bundleCount: number;",
  "  readonly bytes: number;",
  "};",
  "",
].join("\n"));
