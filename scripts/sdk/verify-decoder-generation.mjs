import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildDecoderSnapshot } from "./build-decoder-snapshot.mjs";
import { nativeCanonicalize } from "./native-canonicalize.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const digest = (text) => `0x${createHash("sha256").update(text, "utf8").digest("hex")}`;
const read = (path) => JSON.parse(readFileSync(path, "utf8"));

/**
 * Rebuild the selected UR/Aave additions from their pinned originals while
 * preserving the remaining committed baseline. This is deliberately not a
 * claim that all 804 Registry bundles were rebuilt from their original inputs.
 * Also generate the separate pool regression snapshot consumed by raw tests.
 */
export async function verifyDecoderGeneration({ installProduct = false, log = console.log } = {}) {
  const product = join(root, "packages/core/decoder-snapshots/full");
  const artifact = readFileSync(join(product, "snapshot.json"), "utf8");
  const metadata = read(join(product, "snapshot.meta.json"));
  const container = JSON.parse(artifact);
  assert.equal(metadata.digest, digest(artifact), "committed product digest");
  assert.equal(metadata.bytes, Buffer.byteLength(artifact), "committed product size");
  assert.equal(container.schema_version, 1);
  assert.equal(metadata.bundle_count, container.bundles.length);
  assert.equal(container.bundles.length, 804, "review the baseline when product selection changes");

  const inputs = join(root, "fixtures/sdk/resolved-decoders");
  const selection = read(join(inputs, "selection.json"));
  assert.equal(selection.schema_version, 1);
  assert.equal(selection.manifests.length, 5);
  const selectedIds = new Set(selection.manifests.map((path) => read(join(inputs, path)).id));
  assert.equal(selectedIds.size, 5, "selected manifest IDs must be unique");
  for (const id of selectedIds) {
    assert.equal(container.bundles.filter((bundle) => bundle.id === id).length, 1, `missing or duplicate selected product bundle: ${id}`);
  }

  const temporary = mkdtempSync(join(tmpdir(), "dambi-decoder-rebuild-"));
  try {
    const baseline = { schema_version: 1, bundles: container.bundles.filter((bundle) => !selectedIds.has(bundle.id)) };
    assert.equal(baseline.bundles.length, 799);
    const baselineArtifact = nativeCanonicalize(baseline);
    const staged = join(temporary, "full");
    mkdirSync(staged);
    writeFileSync(join(staged, "snapshot.json"), baselineArtifact);
    writeFileSync(join(staged, "snapshot.meta.json"), JSON.stringify({
      ...metadata, digest: digest(baselineArtifact), bytes: Buffer.byteLength(baselineArtifact),
      bundle_count: baseline.bundles.length,
    }));
    const rebuilt = await buildDecoderSnapshot({
      registryRoot: inputs, outRoot: temporary, addManifests: selection.manifests,
    });
    assert.equal(rebuilt.artifact, artifact, "selected originals must rebuild the exact committed product bytes");
    assert.deepEqual(rebuilt.meta, metadata, "selected reconstruction must preserve product metadata");
    if (installProduct) {
      // Used in the disposable isolated tree: later packaging consumes these
      // regenerated bytes, not merely the copy that bootstrapped the WASM gate.
      for (const name of ["snapshot.json", "snapshot.meta.json"]) {
        copyFileSync(join(staged, name), join(product, name));
      }
    }
    log("[decoder-generation] 799 committed baseline + 5 pinned originals = identical 804-bundle product; Core install passed");
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }

  const selectionFile = join(root, "fixtures/sdk/pool-materialization/selection.json");
  const first = await buildDecoderSnapshot({ selectionFile });
  const second = await buildDecoderSnapshot({ selectionFile });
  assert.equal(first.meta.bundle_count, 3);
  assert.equal(first.meta.selection.route_count, 3);
  assert.deepEqual(first.meta.rejected_by_core, []);
  assert.equal(first.artifact, second.artifact, "selected pool generation must be reproducible");
  assert.deepEqual(first.meta, second.meta);
  log(`[decoder-generation] 3 regression pool bundles: repeated bytes/digest match; Core install passed (${first.meta.bytes} bytes)`);
  return { product: metadata, pools: first.meta };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--install-product")) {
    throw new Error("Usage: node scripts/sdk/verify-decoder-generation.mjs [--install-product]");
  }
  await verifyDecoderGeneration({ installProduct: args.includes("--install-product") });
}
